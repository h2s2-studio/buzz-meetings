import { readFile } from "node:fs/promises";
import { build } from "esbuild";

const check = process.argv.includes("--check");
const result = await build({
  entryPoints: ["src/index.tsx"],
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
  loader: { ".css": "text" },
  minify: true,
  banner: { js: "// Generated by npm run build from src/index.tsx. Apache-2.0." },
  outfile: "plugin.js",
  metafile: true,
  write: !check,
});

if (result.metafile.outputs["plugin.js"].imports.length) {
  throw new Error("Buzz requires a self-contained module");
}
if (check && !(await readFile("plugin.js")).equals(result.outputFiles[0].contents)) {
  throw new Error("plugin.js is stale. Run npm run build and commit it.");
}
